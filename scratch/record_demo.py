import os
import time
import glob
from playwright.sync_api import sync_playwright

def record_demo():
    output_dir = "/config/.gemini/antigravity/brain/ba6da169-c894-44e9-8a8b-1ea6a0164022"
    temp_video_dir = os.path.join(output_dir, "temp_rec")
    os.makedirs(temp_video_dir, exist_ok=True)

    print("Starting Playwright demo recording...")
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        context = browser.new_context(
            viewport={"width": 1280, "height": 800},
            record_video_dir=temp_video_dir,
            record_video_size={"width": 1280, "height": 800}
        )
        page = context.new_page()

        print("Navigating to https://wanderlust-frontend-447988840851.us-east1.run.app...")
        page.goto("https://wanderlust-frontend-447988840851.us-east1.run.app")
        page.wait_for_selector("#input", timeout=10000)
        time.sleep(2)

        # --- Prompt 1: Core Travel Concierge Itinerary & A2UI Cards ---
        prompt1 = "Suggest a 3-day luxury travel itinerary for Paris with top hotel recommendations and interactive cards."
        print(f"Sending Prompt 1: {prompt1}")
        page.type("#input", prompt1, delay=35)
        time.sleep(0.8)
        page.click("button.send-btn")

        # Wait for reply to appear and typing indicator to complete
        print("Waiting for Prompt 1 response...")
        time.sleep(16)

        # --- Prompt 2: Tool call, Database Lookup & Image Generation ---
        prompt2 = "Check live weather in Tokyo and generate a visual postcard image for it!"
        print(f"Sending Prompt 2: {prompt2}")
        page.type("#input", prompt2, delay=35)
        time.sleep(0.8)
        page.click("button.send-btn")

        # Wait for reply, tool execution, and generated image card
        print("Waiting for Prompt 2 response...")
        time.sleep(22)

        time.sleep(3)
        context.close()
        browser.close()

    # Find the recorded video file
    videos = glob.glob(os.path.join(temp_video_dir, "*.webm"))
    if videos:
        final_path = os.path.join(output_dir, "agent_demo_video.webm")
        os.rename(videos[0], final_path)
        print(f"Demo video successfully recorded and saved to: {final_path}")
    else:
        print("Error: No video file was generated by Playwright.")

if __name__ == "__main__":
    record_demo()
